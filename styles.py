STYLE_KEYS = ("auto", "study", "code")


def normalize_style(value: str | None) -> str:
    """Неизвестный или пустой стиль превращается в универсальный."""
    key = (value or "").strip().lower()
    return key if key in STYLE_HINTS else DEFAULT_STYLE


def style_hint(value: str | None) -> str | None:
    return STYLE_HINTS.get(normalize_style(value))


def style_title(value: str | None) -> str:
    return STYLE_TITLES.get(normalize_style(value), STYLE_TITLES[DEFAULT_STYLE])