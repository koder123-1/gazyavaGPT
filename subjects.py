_BY_KEY = {subject.key: subject for subject in SUBJECTS}
_COMPILED: tuple[tuple[Subject, tuple[tuple[re.Pattern[str], int], ...]], ...] = tuple(
    (
        subject,
        tuple(
            (re.compile(pattern, re.IGNORECASE | re.UNICODE), weight)
            for pattern, weight in subject.patterns
        ),
    )
    for subject in SUBJECTS
)


def subject_title(key: str) -> str:
    """Человеческое название предмета; для ``general`` — пусто."""
    subject = _BY_KEY.get(key)
    return subject.title if subject else ""


def subject_hint(key: str) -> str:
    """Блок правил для системного промпта. Пустая строка — без предмета."""
    subject = _BY_KEY.get(key)
    return subject.hint if subject else ""


def detect_subject(text: str | None, *, has_image: bool = False) -> str:
    """Возвращает ключ предмета или ``general``.

    Баллы складываются по совпадениям шаблонов, у каждого шаблона есть вес.
    Порог в 2 балла отсекает случайные общие слова: «реши» само по себе ещё не
    делает вопрос математикой, а «реши уравнение» — делает.
    """
    low = (text or "").lower()
    if not low.strip():
        return GENERAL

    best_key = GENERAL
    best_score = 0
    for subject, patterns in _COMPILED:
        score = 0
        for regex, weight in patterns:
            found = len(regex.findall(low))
            if found:
                score += min(found, 3) * weight
        if score > best_score:
            best_key, best_score = subject.key, score

    if best_score < 2:
        # Фото без подписи: предмет определит vision-модель по самой картинке.
        return GENERAL
    return best_key